// Builds web/public/i18n/de.js, the dictionary of the German interface
// overlay (web/public/i18n/silo-i18n.js), from de.tsv.
//
//   node deploy/windows/i18n/build-de.js
//
// Each de.tsv line is English<TAB>German. {0}, {1} ... mark parts that change.
// German may drop a placeholder that is an English plural ending ("file{1}")
// but must not add one. Placeholders are typed so a pattern cannot swallow a
// media title such as "The Super Mario Bros. Movie" ("{0} movie"):
//   {~n} plural ending right after a letter: 0-3 lowercase letters
//   {#n} in short patterns (two literal words or fewer): starts with a digit
//   {n}  any text: longer sentences, and the short ones in text-placeholders.txt
const fs = require('fs');
const path = require('path');

const here = __dirname;
const out = path.resolve(here, '../../../web/public/i18n/de.js');
const exact = {};
const patterns = {};
const problems = [];

const lines = fs.readFileSync(path.join(here, 'de.tsv'), 'utf8').split(/\r?\n/);
lines.forEach((line, i) => {
  if (!line.trim() || line.startsWith('#')) return;
  const tab = line.indexOf('\t');
  if (tab < 0) return problems.push(`line ${i + 1}: no tab`);
  const en = line.slice(0, tab).replace(/\s+/g, ' ').trim();
  const de = line.slice(tab + 1).trim();
  if (!en || !de || en === de) return;
  const enSet = new Set(en.match(/\{\d+\}/g) || []);
  const extra = (de.match(/\{\d+\}/g) || []).filter((p) => !enSet.has(p));
  const dropped = [...enSet].filter((p) => !de.includes(p));
  const pluralOnly = (p) => new RegExp('[a-z]' + p.replace(/[{}]/g, '\\$&') + '(\\s|$|[.,)])').test(en);
  if (extra.length || dropped.some((p) => !pluralOnly(p))) {
    return problems.push(`line ${i + 1}: placeholders differ: ${en} -> ${de}`);
  }
  const target = enSet.size ? patterns : exact;
  if (en in target) return; // first entry wins
  target[en] = de;
});

// A pattern of only placeholders and punctuation would match anything.
for (const k of Object.keys(patterns)) if (!/[A-Za-z]{2}/.test(k.replace(/\{\d+\}/g, ''))) delete patterns[k];

const textOk = new Set(
  fs.readFileSync(path.join(here, 'text-placeholders.txt'), 'utf8')
    .split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith('#')),
);
const typed = {};
for (const [en, de] of Object.entries(patterns)) {
  const literalWords = (en.replace(/\{\d+\}/g, ' ').match(/[A-Za-z][A-Za-z'’-]*/g) || []).length;
  const key = en.replace(/\{(\d+)\}/g, (m, n, off) => {
    const before = en[off - 1] || '';
    const after = en[off + m.length] || '';
    if (/[a-z]/.test(before) && (!after || /[\s.,)!?:]/.test(after))) return `{~${n}}`;
    if (literalWords <= 2 && !textOk.has(en)) return `{#${n}}`;
    return m;
  });
  typed[key] = de;
}

const header = '/* German dictionary for /i18n/silo-i18n.js. Generated by deploy/windows/i18n/build-de.js from de.tsv; edit de.tsv, not this file. */\n';
fs.writeFileSync(out, header + 'window.__SILO_I18N_DE = ' + JSON.stringify({ exact, patterns: typed }) + ';\n');
console.log(`exact ${Object.keys(exact).length}, patterns ${Object.keys(typed).length}, ${fs.statSync(out).size} bytes -> ${out}`);
if (problems.length) {
  console.log(`${problems.length} problem(s):`);
  problems.forEach((p) => console.log('  ' + p));
  process.exitCode = 1;
}
