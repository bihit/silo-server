<#
.SYNOPSIS
  Puts HTTPS in front of Silo: Caddy on port 443 for one domain, forwarding to
  Silo on 127.0.0.1:8020, as the Windows service silo-caddy.
.DESCRIPTION
  Needs Administrator rights once, for the service registration.
  - Caddy comes from the official GitHub release; the zip is checked against
    the release's SHA-512 checksum list before it is unpacked.
  - The certificate comes from Let's Encrypt through the TLS-ALPN challenge on
    port 443. Port 80 is never bound (no HTTP challenge, no HTTP redirect), so
    whatever listens there stays untouched.
  - Only HTTP/1.1 and HTTP/2 are served (TCP 443); HTTP/3 would need UDP 443.
  - The admin API is off. Certificates and Caddy state live in data\caddy,
    logs in logs\caddy, the generated Caddyfile next to caddy.exe in
    runtime\caddy. The config folder with Silo's secrets is not shared.
  - The service runs as NT SERVICE\silo-caddy, with write access only to its
    own data and log folders.
  - No firewall rule is created; port 443 must already be reachable.
  Re-running with the same domain updates the files and the registration.
.PARAMETER Domain
  The host name whose DNS A record points at this server without a proxy.
.EXAMPLE
  .\Install-SiloHttps.ps1 -Domain silo.example.org
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][ValidatePattern('^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$')][string]$Domain,
    [string]$CaddyVersion = '2.11.7'
)
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'SiloWindows.psm1') -Force
Assert-SiloAdmin 'den Dienst silo-caddy registrieren und Ordnerrechte setzen'
$layout = Get-SiloLayout
$ports = Get-SiloPorts
$name = 'silo-caddy'
$caddyHome = Join-Path $layout.Runtime 'caddy'
$caddyExe = Join-Path $caddyHome 'caddy.exe'
$caddyData = Join-Path $layout.Data 'caddy'
$caddyLogs = Join-Path $layout.Logs 'caddy'
$caddyfile = Join-Path $caddyHome 'Caddyfile'

Write-SiloStep "Port 443 pruefen"
$owner = Get-NetTCPConnection -State Listen -LocalPort 443 -ErrorAction SilentlyContinue | Select-Object -First 1
if ($owner) {
    $proc = Get-Process -Id $owner.OwningProcess -ErrorAction SilentlyContinue
    if (-not $proc -or $proc.Path -ne $caddyExe) { throw "Port 443 ist belegt ($($proc.ProcessName)). Nichts wurde geaendert." }
}
Write-SiloOk 'frei oder bereits von silo-caddy belegt'

Write-SiloStep "Caddy $CaddyVersion"
$base = "https://github.com/caddyserver/caddy/releases/download/v$CaddyVersion"
$zipName = "caddy_${CaddyVersion}_windows_amd64.zip"
$sumName = "caddy_${CaddyVersion}_checksums.txt"
$dl = Join-Path $layout.InstallRoot "downloads\caddy-$CaddyVersion"
New-Item -ItemType Directory -Force $dl | Out-Null
foreach ($f in $zipName, $sumName) {
    $target = Join-Path $dl $f
    if (-not (Test-Path -LiteralPath $target)) { Invoke-WebRequest -UseBasicParsing -Uri "$base/$f" -OutFile $target }
}
$expected = (Get-Content (Join-Path $dl $sumName) | Where-Object { $_ -match "\s$([regex]::Escape($zipName))$" } | ForEach-Object { ($_ -split '\s+')[0] }) | Select-Object -First 1
$actual = (Get-FileHash -Algorithm SHA512 -LiteralPath (Join-Path $dl $zipName)).Hash
if (-not $expected -or $actual -ne $expected.ToUpperInvariant()) { throw "Pruefsumme von $zipName stimmt nicht. Nichts wurde installiert." }
Write-SiloOk 'SHA-512 stimmt mit der Release-Liste ueberein'
$existing = Get-Service -Name $name -ErrorAction SilentlyContinue
if ($existing -and $existing.Status -ne 'Stopped') { Stop-Service -Name $name -Force }
$unpack = Join-Path $dl 'unpacked'
if (Test-Path -LiteralPath $unpack) { Remove-Item -Recurse -Force -LiteralPath $unpack }
Expand-Archive -LiteralPath (Join-Path $dl $zipName) -DestinationPath $unpack
New-Item -ItemType Directory -Force $caddyHome | Out-Null
Copy-Item -Force (Join-Path $unpack 'caddy.exe') $caddyExe
Write-SiloOk $caddyExe

Write-SiloStep 'Caddyfile'
foreach ($d in $caddyData, $caddyLogs) { New-Item -ItemType Directory -Force $d | Out-Null }
$dataFwd = $caddyData -replace '\\', '/'
$content = @"
# Generated by Install-SiloHttps.ps1. Re-run the script instead of editing.
{
	admin off
	auto_https disable_redirects
	storage file_system "$dataFwd"
	servers {
		protocols h1 h2
	}
}

$Domain {
	tls {
		issuer acme {
			disable_http_challenge
		}
	}
	reverse_proxy 127.0.0.1:$($ports.Silo) {
		flush_interval -1
	}
}
"@
Set-Content -LiteralPath $caddyfile -Value $content -Encoding ascii
Invoke-SiloNative -FilePath $caddyExe -What 'caddy validate' -Arguments @('validate', '--config', $caddyfile, '--adapter', 'caddyfile') | Out-Null
Write-SiloOk $caddyfile

Write-SiloStep $name
if ($existing) {
    Invoke-SiloNative -FilePath "$env:SystemRoot\System32\sc.exe" -What "sc delete $name" -Arguments @('delete', $name) | Out-Null
    Start-Sleep -Seconds 2
}
Invoke-SiloNative -FilePath $layout.Shawl -What 'shawl add (caddy)' -Arguments @(
    'add', '--name', $name, '--cwd', $caddyHome,
    '--env', "XDG_DATA_HOME=$caddyData", '--env', "XDG_CONFIG_HOME=$caddyData",
    '--log-dir', $caddyLogs, '--log-cmd-as', 'caddy', '--log-rotate', 'daily', '--log-retain', '14',
    '--stop-timeout', '20000', '--restart-if-not', '0', '--restart-delay', '5000', '--kill-process-tree',
    '--', $caddyExe, 'run', '--config', $caddyfile, '--adapter', 'caddyfile')
$sc = "$env:SystemRoot\System32\sc.exe"
Invoke-SiloNative -FilePath $sc -Arguments @('config', $name, 'start=', 'delayed-auto', 'obj=', "NT SERVICE\$name") -What "sc config $name" | Out-Null
Invoke-SiloNative -FilePath $sc -Arguments @('description', $name, "HTTPS fuer Silo: $Domain auf Port 443 -> 127.0.0.1:$($ports.Silo)") -What "sc description $name" | Out-Null
$acct = "NT SERVICE\$name"
Grant-SiloAccess -Path $caddyData -Account $acct -Rights Modify
Grant-SiloAccess -Path $caddyLogs -Account $acct -Rights Modify
Grant-SiloAccess -Path $caddyHome -Account $acct -Rights ReadAndExecute
Start-Service -Name $name
Write-SiloOk "$acct, gestartet"
Write-Host "Zertifikat und Weiterleitung pruefen: https://$Domain/api/v1/health"
